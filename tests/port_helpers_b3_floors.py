"""Helpers for the template count-floor port (batch b3-floors).

Stand-in: ``tests/fixtures/b3-floors/`` holds a fictional bike-shop template
(``universal/Performance.SemanticModel``) and ``variants.json``: named client
variants, each a list of text operations applied to a copy of the template.
The same variants were run through the ORIGINAL tests to record the verdicts
in ``parity-expected.json``.

Count-floor finding contract assumed by these tests (E-template-count-floor):
a ``model.count_below_template`` finding in ``detect --json`` carries a
``data`` object with ``metric`` (one of ``measures``, ``dax_expressions``,
``nameof_references``, ``relationships``, ``many_to_one``, ``family_tables``,
``table_columns``, ``family_table_refs``), the integers ``client``,
``template``, ``adjustment`` and ``floor``, ``table`` for the per-table
metrics (``table_columns``, ``family_table_refs``; absent for a total) and
``missing`` (list of table names) for ``family_tables``.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from conftest import FIXTURES, drift, write_fleet

STANDIN = FIXTURES / "b3-floors"
TEMPLATE_REL = Path("universal") / "Performance.SemanticModel"
MODEL = "bike-shop"
COUNT_KIND = "model.count_below_template"
STARTER_ALLOWLIST = ["measure.missing", "measure.expression_drift",
                     "measure.property_drift", "column.missing",
                     "relationship.missing"]


def variants() -> dict:
    return json.loads((STANDIN / "variants.json").read_text(encoding="utf-8"))


def baseline() -> dict:
    """The stand-in's integration baseline, generated by the ORIGINAL capture
    test from the same template (renamed)."""
    return json.loads((STANDIN / "integration_baseline.json").read_text(encoding="utf-8"))


def apply_variant(definition: Path, ops: list) -> None:
    for op in ops:
        target = Path(definition) / op["path"]
        if op["op"] == "delete":
            target.unlink()
        elif op["op"] == "write":
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(op["text"], encoding="utf-8")
        elif op["op"] == "replace":
            text = target.read_text(encoding="utf-8")
            assert text.count(op["old"]) == 1, (op["path"], op["old"])
            target.write_text(text.replace(op["old"], op["new"]), encoding="utf-8")
        else:
            raise ValueError(op["op"])


def model_copy(dst: Path, variant: str = "clean") -> Path:
    shutil.copytree(STANDIN / TEMPLATE_REL, dst)
    apply_variant(dst / "definition", variants()[variant])
    return dst


def build_fleet(tmp_path: Path, variant: str, *, allow=None, overrides=None,
                entry_extra: dict | None = None, capture: bool = True) -> Path:
    """tmp fleet: the template plus one derived model ``bike-shop`` built from
    ``variant``. ``allow`` defaults to every count-floor-adjacent kind."""
    template = tmp_path / TEMPLATE_REL
    shutil.copytree(STANDIN / TEMPLATE_REL, template)
    client = model_copy(tmp_path / MODEL / "Performance.SemanticModel", variant)
    entry = {"path": client}
    if overrides:
        entry["overrides"] = overrides
    entry.update(entry_extra or {})
    kinds = allow if allow is not None else STARTER_ALLOWLIST + [
        "table.missing", "relationship.modified", "relationship.casing_mismatch"]
    fy = write_fleet(tmp_path, template, {MODEL: entry},
                     allowlist={"kinds": kinds})
    if capture:
        r = drift("capture", fleet=fy)
        assert r.exit_code == 0, r.output
    return fy


def detect(fy: Path, *args):
    r = drift("detect", "--json", *args, fleet=fy)
    assert r.exit_code in (0, 1), r.output
    return r, json.loads(r.stdout)


def findings(report: dict, kind: str | None = None, model: str = MODEL) -> list:
    out = report["models"][model]["findings"]
    return [f for f in out if kind is None or f["kind"] == kind]


def overridden(report: dict, model: str = MODEL) -> list:
    return report["models"][model]["overridden"]


def count_findings(report: dict, metric: str, model: str = MODEL) -> list:
    return [f for f in findings(report, COUNT_KIND, model)
            if (f.get("data") or {}).get("metric") == metric]


def refs(report: dict, kind: str, model: str = MODEL) -> list:
    return sorted(f["ref"] for f in findings(report, kind, model))


def vparams(rows):
    """pytest params whose id is the variant name (first value of each row)."""
    import pytest
    return [pytest.param(*row, id=row[0]) for row in rows]
